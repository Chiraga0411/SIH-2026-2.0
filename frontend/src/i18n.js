/* ---------- runtime translator: swaps text in the DOM, remembers the English original ---------- */
const norm = s => s.replace(/\s+/g, ' ').trim();
const ATTRS = ['placeholder', 'aria-label', 'title'];
const SKIP = new Set(['SCRIPT', 'STYLE', 'TEXTAREA']);
const texts = new WeakMap(),
    attrs = new WeakMap();
let LANG = 'en',
    root = null;

function tText(n) {
    if (!n.parentNode || SKIP.has(n.parentNode.nodeName)) return;
    const cur = n.nodeValue;
    let r = texts.get(n);
    if (!r || cur !== r.shown) {
        r = { orig: cur, shown: cur };
        texts.set(n, r)
    } // React wrote new English text
    const hi = LANG === 'hi' ? HI[norm(r.orig)] : undefined;
    const want = hi ? r.orig.match(/^\s*/)[0] + hi + r.orig.match(/\s*$/)[0] : r.orig;
    if (cur !== want) n.nodeValue = want;
    r.shown = want;
}

function tAttr(el) {
    let m = attrs.get(el);
    if (!m) {
        m = {};
        attrs.set(el, m)
    }
    for (const a of ATTRS) {
        const cur = el.getAttribute(a);
        if (cur == null) continue;
        let r = m[a];
        if (!r || cur !== r.shown) {
            r = { orig: cur, shown: cur };
            m[a] = r
        }
        const hi = LANG === 'hi' ? HI[norm(r.orig)] : undefined,
            want = hi || r.orig;
        if (cur !== want) el.setAttribute(a, want);
        r.shown = want;
    }
}

function walk(n) {
    if (n.nodeType === 3) { tText(n); return }
    if (n.nodeType !== 1 || n.hasAttribute('data-notr')) return;
    tAttr(n);
    n.childNodes.forEach(walk);
}

export function initTranslator() {
    if (root) return;
    root = document.getElementById('root') || document.body;
    new MutationObserver(ms => {
        for (const m of ms) {
            if (m.type === 'characterData') tText(m.target);
            else if (m.type === 'attributes') tAttr(m.target);
            else m.addedNodes.forEach(walk);
        }
    }).observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
    walk(root);
}
export function applyLang(l) {
    LANG = l === 'hi' ? 'hi' : 'en';
    document.documentElement.lang = LANG;
    if (root) walk(root);
}
export const readLang = () => { try { return localStorage.getItem('ls-lang') === 'hi' ? 'hi' : 'en' } catch { return 'en' } };
export const saveLang = l => { try { localStorage.setItem('ls-lang', l) } catch {} };